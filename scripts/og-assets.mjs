/**
 * Embeds the Open Graph fonts and a small circular-crop avatar into lib/og-assets.generated.ts.
 *
 * Why: Cloudflare Workers have no filesystem at runtime, so next/og can't readFile() fonts or the portrait.
 * Inlining them keeps OG images working identically under `next build` and vinext/Workers.
 * Re-run after changing content/site.ts `portrait` (e.g. flipping USE_OFFICIAL_PORTRAIT): npm run og:assets
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { portrait } from "../content/site.ts";

const root = path.resolve(import.meta.dirname, "..");
const AVATAR = 176; // 2× the 88 px avatar drawn on the card

const font = (name) => readFile(path.join(root, "app/fonts/og", name)).then((b) => b.toString("base64"));

async function avatar() {
  const src = path.join(root, "public", portrait.src);
  const img = sharp(src);
  const { width, height } = await img.metadata();
  const [fx, fy] = portrait.circle.focal.split(" ").map((p) => parseFloat(p) / 100);
  const side = Math.round(Math.min(width, height) / Math.max(1, portrait.circle.zoom));
  const clamp = (v, max) => Math.max(0, Math.min(max, Math.round(v)));
  const left = clamp(fx * width - side / 2, width - side);
  const top = clamp(fy * height - side / 2, height - side);
  const out = await img.extract({ left, top, width: side, height: side }).resize(AVATAR, AVATAR).jpeg({ quality: 82, mozjpeg: true }).toBuffer();
  return `data:image/jpeg;base64,${out.toString("base64")}`;
}

const [regular, semibold, photo] = await Promise.all([font("hanken-grotesk-latin-400-normal.woff"), font("hanken-grotesk-latin-600-normal.woff"), avatar()]);

const file = `// Generated by scripts/og-assets.mjs from ${portrait.src} and app/fonts/og. Do not edit by hand.
export const ogPortraitSrc = ${JSON.stringify(portrait.src)};
export const ogPhoto = ${JSON.stringify(photo)};
export const ogFontRegular = ${JSON.stringify(regular)};
export const ogFontSemibold = ${JSON.stringify(semibold)};
`;
await writeFile(path.join(root, "lib/og-assets.generated.ts"), file);
console.log(`og assets: avatar ${Math.round(photo.length / 1024)} KB (base64), fonts ${Math.round((regular.length + semibold.length) / 1024)} KB`);
